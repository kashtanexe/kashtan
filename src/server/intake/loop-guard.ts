import { getHeader, type PostmarkHeader } from "@/lib/email/types";

export const CHALLENGE_COOLDOWN_DAYS = 30;

export interface LoopGuardInput {
  /** Address we would send a challenge to. */
  senderEmail: string;
  subject?: string;
  /** Headers of the message written by the sender (the original, for forwards when available). */
  headers?: PostmarkHeader[];
  /** Last time we challenged this sender on behalf of this exec, if ever. */
  lastChallengeAt?: string | null;
  /** Sender is on the suppression list (bounce, complaint, opt-out). */
  suppressed?: boolean;
  /** Our own domains: never challenge ourselves. */
  ownDomains?: string[];
  now?: Date;
}

export type LoopGuardResult = { allowed: true } | { allowed: false; reason: LoopGuardReason; detail: string };

export type LoopGuardReason =
  | "auto_submitted"
  | "bulk_precedence"
  | "mailing_list"
  | "noreply_sender"
  | "autoreply_subject"
  | "autoreply_header"
  | "own_domain"
  | "suppressed"
  | "rate_limited"
  | "invalid_sender";

const NOREPLY_LOCAL = /^(no[-_.]?reply|do[-_.]?not[-_.]?reply|donotreply|mailer[-_.]?daemon|postmaster|bounces?|notifications?|alerts?|auto[-_.]?(reply|confirm)|system)([+._-].*)?$/i;

const AUTOREPLY_SUBJECT = [
  /^\s*(auto(matic)?[\s-]*(reply|response)|autoreply)\b/i,
  /\bout of (the )?office\b/i,
  /\bOOO\b/,
  /^\s*r[ée]ponse automatique\b/i,
  /\babsence du bureau\b/i,
  /\babwesenheit(snotiz)?\b/i,
  /^\s*automatische (antwort|r[üu]ckmeldung)\b/i,
  /\bafwezig(heid)?\b/i,
  /^\s*automatisch antwoord\b/i,
  /^\s*respuesta autom[áa]tica\b/i,
  /\bfuera de la oficina\b/i,
  /^\s*(undeliverable|delivery status notification|mail delivery failed|returned mail)\b/i,
];

export function checkLoopGuard(input: LoopGuardInput): LoopGuardResult {
  const email = input.senderEmail.trim().toLowerCase();
  const [local, domain] = email.split("@");
  if (!local || !domain || !domain.includes(".")) {
    return { allowed: false, reason: "invalid_sender", detail: `Not a valid address: ${input.senderEmail}` };
  }

  if (input.ownDomains?.some((d) => domain === d.toLowerCase() || domain.endsWith(`.${d.toLowerCase()}`))) {
    return { allowed: false, reason: "own_domain", detail: "Sender is one of our own domains" };
  }

  if (NOREPLY_LOCAL.test(local)) {
    return { allowed: false, reason: "noreply_sender", detail: `No-reply style sender: ${local}@` };
  }

  const h = input.headers;
  const autoSubmitted = getHeader(h, "Auto-Submitted");
  if (autoSubmitted && autoSubmitted.trim().toLowerCase() !== "no") {
    return { allowed: false, reason: "auto_submitted", detail: `Auto-Submitted: ${autoSubmitted}` };
  }

  const precedence = getHeader(h, "Precedence")?.toLowerCase().trim();
  if (precedence && ["bulk", "junk", "list", "auto_reply"].includes(precedence)) {
    return { allowed: false, reason: "bulk_precedence", detail: `Precedence: ${precedence}` };
  }

  const listHeader = (h ?? []).find((x) => /^list-(id|unsubscribe|post|help)$/i.test(x.Name));
  if (listHeader) {
    return { allowed: false, reason: "mailing_list", detail: `${listHeader.Name} header present` };
  }

  const autoHeaders = ["X-Autoreply", "X-Autorespond", "X-Auto-Response-Suppress", "X-Autogenerated"];
  for (const name of autoHeaders) {
    const v = getHeader(h, name);
    if (v && !(name === "X-Auto-Response-Suppress" && /^none$/i.test(v.trim()))) {
      return { allowed: false, reason: "autoreply_header", detail: `${name}: ${v}` };
    }
  }

  if (input.subject && AUTOREPLY_SUBJECT.some((re) => re.test(input.subject!))) {
    return { allowed: false, reason: "autoreply_subject", detail: `Auto-reply subject: "${input.subject}"` };
  }

  if (input.suppressed) {
    return { allowed: false, reason: "suppressed", detail: "Sender is on the suppression list" };
  }

  if (input.lastChallengeAt) {
    const now = input.now ?? new Date();
    const ageDays = (now.getTime() - new Date(input.lastChallengeAt).getTime()) / 86_400_000;
    if (ageDays < CHALLENGE_COOLDOWN_DAYS) {
      return {
        allowed: false,
        reason: "rate_limited",
        detail: `Already challenged ${Math.floor(ageDays)} day(s) ago (max one per ${CHALLENGE_COOLDOWN_DAYS} days)`,
      };
    }
  }

  return { allowed: true };
}
